# Cuts the chosen moments out of clients' voice notes and writes voices.js (file, length, waveform).
#   python3 tools/voices.py <folder with the original voice notes>
# The originals stay outside the site; only the short cuts in audio/ are published.
# Cuts are listed in tools/voice-cuts.json: [client id, original file name, [[start, end], ...]].
import json, os, struct, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "_voice_src")
CUTS = json.load(open(os.path.join(ROOT, "tools", "voice-cuts.json")))
BARS = 38

def peaks(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", "8000", "-f", "s16le", "-"],
                         capture_output=True, check=True).stdout
    n = len(raw) // 2
    samples = struct.unpack(f"<{n}h", raw[: n * 2])
    size = max(1, n // BARS)
    rms = []
    for i in range(BARS):
        chunk = samples[i * size:(i + 1) * size] or (0,)
        rms.append((sum(s * s for s in chunk) / len(chunk)) ** 0.5)
    top = max(rms) or 1
    return [round(max(0.08, (r / top) ** 0.8), 3) for r in rms]

def length(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                         capture_output=True, text=True, check=True).stdout
    return round(float(out), 2)

voices = {}
os.makedirs(os.path.join(ROOT, "audio"), exist_ok=True)
for client, name, parts in CUTS:
    n = len(voices.get(client, [])) + 1
    out = os.path.join(ROOT, "audio", f"{client}-{n}.m4a")
    # Each part is [start, end] in seconds; several parts are joined with a short crossfade.
    inputs, chains = [], []
    for k, (start, end) in enumerate(parts):
        inputs += ["-ss", str(start), "-t", str(end - start), "-i", os.path.join(SRC, name)]
        chains.append(f"[{k}:a]aresample=44100,aformat=channel_layouts=mono[p{k}]")
    graph = ";".join(chains)
    last = "p0"
    for k in range(1, len(parts)):
        graph += f";[{last}][p{k}]acrossfade=d=0.12:c1=tri:c2=tri[x{k}]"
        last = f"x{k}"
    tmp = out + ".wav"
    subprocess.run(["ffmpeg", "-v", "error", "-y", *inputs, "-filter_complex", graph, "-map", f"[{last}]", tmp], check=True)
    dur = length(tmp)
    fade = min(0.2, dur / 8)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", tmp,
                    "-af", f"afade=t=in:d=0.05,afade=t=out:st={dur - fade:.2f}:d={fade},loudnorm=I=-16:TP=-1.5:LRA=11",
                    "-ac", "1", "-ar", "44100", "-c:a", "aac", "-b:a", "80k", "-movflags", "+faststart", out], check=True)
    os.remove(tmp)
    voices.setdefault(client, []).append({"src": f"/audio/{client}-{n}.m4a", "dur": length(out), "peaks": peaks(out)})

with open(os.path.join(ROOT, "voices.js"), "w") as f:
    f.write("// Generated by tools/voices.py: cut voice notes per client, with their length and waveform.\n")
    f.write("const VOICES = " + json.dumps(voices, separators=(",", ":")) + ";\n")
print({k: [v["dur"] for v in vs] for k, vs in voices.items()})
